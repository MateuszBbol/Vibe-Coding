function normalizeProductName(name: string): string {
  return name
    .trim()
    .toLocaleLowerCase('pl-PL')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ');
}

const aliasesByNormalizedName = new Map<string, ShoppingCategoryId>();
const normalizedAliases: { alias: string; categoryId: ShoppingCategoryId }[] = [];

for (const [categoryId, aliases] of Object.entries(productAliases) as [
  Exclude<ShoppingCategoryId, 'other'>,
  readonly string[],
][]) {
  for (const alias of aliases) {
    const normalizedAlias = normalizeProductName(alias);
    if (!aliasesByNormalizedName.has(normalizedAlias)) {
      aliasesByNormalizedName.set(normalizedAlias, categoryId);
      normalizedAliases.push({ alias: normalizedAlias, categoryId });
    }
  }
}

normalizedAliases.sort((left, right) => right.alias.length - left.alias.length);

export const productCategoryAliasCount = normalizedAliases.length;

export function classifyShoppingProduct(name: string): ShoppingCategoryId {
  const normalizedName = normalizeProductName(name);
  const exactMatch = aliasesByNormalizedName.get(normalizedName);
  if (exactMatch) {
    return exactMatch;
  }

  const prefixMatch = normalizedAliases.find(({ alias }) => {
    if (!normalizedName.startsWith(alias)) {
      return false;
    }
    const nextCharacter = normalizedName.charAt(alias.length);
    return !nextCharacter || !/[\p{L}\p{N}]/u.test(nextCharacter);
  });

  return prefixMatch?.categoryId ?? getShoppingCategory(null).id;
}

export function categoryAfterProductNameChange(
  name: string,
  currentCategory: string | null,
  manuallyOverridden: boolean,
): ShoppingCategoryId {
  return manuallyOverridden && currentCategory
    ? getShoppingCategory(currentCategory).id
    : classifyShoppingProduct(name);
}
